// Generates supabase/seed.sql from the static menu so the database and the
// front-end share the same slugs. Run with: npm run db:seed:generate
import { writeFileSync } from "node:fs";
import { ITALIAN_MENU_ITEMS } from "../src/data/italian-menu.ts";
import { translate } from "../src/i18n/translations.ts";

const CATEGORY_ORDER = [
  "appetizers",
  "pasta",
  "pizza",
  "main-courses",
  "specials",
  "sandwiches",
  "sides",
  "desserts",
  "drinks",
];

const STAFF = [
  { id: "00000000-0000-4000-8000-000000000001", email: "admin@bellacucina.local", role: "admin" },
  { id: "00000000-0000-4000-8000-000000000002", email: "garcom@bellacucina.local", role: "waiter" },
  { id: "00000000-0000-4000-8000-000000000003", email: "cozinha@bellacucina.local", role: "kitchen" },
];
const STAFF_PASSWORD = "bella123";

const sql = (value) =>
  value === null || value === undefined ? "NULL" : `'${String(value).replace(/'/g, "''")}'`;

const usedCategories = CATEGORY_ORDER.filter((slug) =>
  ITALIAN_MENU_ITEMS.some((item) => item.category === slug),
);

const lines = [
  "-- Generated by scripts/generate-seed.mjs. Do not edit by hand.",
  "",
  "-- Menu categories",
  "INSERT INTO menu_categories (slug, name_pt, name_en, name_it, \"order\") VALUES",
  usedCategories
    .map(
      (slug, index) =>
        `(${sql(slug)}, ${sql(translate("pt", `menu.category.${slug}`))}, ${sql(
          translate("en", `menu.category.${slug}`),
        )}, ${sql(translate("it", `menu.category.${slug}`))}, ${index})`,
    )
    .join(",\n") + "",
  "ON CONFLICT (slug) DO UPDATE SET name_pt = EXCLUDED.name_pt, name_en = EXCLUDED.name_en, name_it = EXCLUDED.name_it, \"order\" = EXCLUDED.\"order\";",
  "",
  "-- Menu items (names and descriptions are only available in Portuguese for now)",
  "INSERT INTO menu_items (slug, category_id, name_pt, name_en, name_it, description_pt, description_en, description_it, price, image_url, popular, \"order\")",
  "SELECT v.slug, c.id, v.name, v.name, v.name, v.description, v.description, v.description, v.price, v.image_url, v.popular, v.position",
  "FROM (VALUES",
  ITALIAN_MENU_ITEMS.map(
    (item, index) =>
      `  (${sql(item.id)}, ${sql(item.category)}, ${sql(item.name)}, ${sql(item.description)}, ${item.price.toFixed(
        2,
      )}::NUMERIC, ${sql(item.image)}, ${item.featured ? "TRUE" : "FALSE"}, ${index})`,
  ).join(",\n"),
  ") AS v(slug, category_slug, name, description, price, image_url, popular, position)",
  "JOIN menu_categories c ON c.slug = v.category_slug",
  "ON CONFLICT (slug) DO UPDATE SET category_id = EXCLUDED.category_id, name_pt = EXCLUDED.name_pt, description_pt = EXCLUDED.description_pt, price = EXCLUDED.price, image_url = EXCLUDED.image_url, popular = EXCLUDED.popular, \"order\" = EXCLUDED.\"order\";",
  "",
  `-- Local staff accounts (password: ${STAFF_PASSWORD}). Never run this seed in production.`,
  ...STAFF.flatMap(({ id, email, role }) => [
    `INSERT INTO auth.users (instance_id, id, aud, role, email, encrypted_password, email_confirmed_at, raw_app_meta_data, raw_user_meta_data, created_at, updated_at, confirmation_token, email_change, email_change_token_new, recovery_token)`,
    `VALUES ('00000000-0000-0000-0000-000000000000', ${sql(id)}, 'authenticated', 'authenticated', ${sql(email)}, extensions.crypt(${sql(STAFF_PASSWORD)}, extensions.gen_salt('bf')), NOW(), '{"provider":"email","providers":["email"]}', '{}', NOW(), NOW(), '', '', '', '')`,
    "ON CONFLICT (id) DO NOTHING;",
    `INSERT INTO auth.identities (id, user_id, provider_id, identity_data, provider, last_sign_in_at, created_at, updated_at)`,
    `VALUES (${sql(id)}, ${sql(id)}, ${sql(id)}, jsonb_build_object('sub', ${sql(id)}, 'email', ${sql(email)}), 'email', NOW(), NOW(), NOW())`,
    "ON CONFLICT DO NOTHING;",
    `INSERT INTO staff_members (user_id, role) VALUES (${sql(id)}, ${sql(role)}) ON CONFLICT (user_id) DO UPDATE SET role = EXCLUDED.role;`,
    "",
  ]),
];

writeFileSync(new URL("../supabase/seed.sql", import.meta.url), lines.join("\n"));
console.log(`seed.sql: ${usedCategories.length} categories, ${ITALIAN_MENU_ITEMS.length} items, ${STAFF.length} staff`);
